# Python Dictionaries

student = {
    "name": "Yatharth",
    "age": 20,
    "course": "B.Tech IT",
    "skills": ["Python", "Java", "Machine Learning"]
}

print("Name:", student["name"])
print("Age:", student["age"])
print("Course:", student["course"])
print("Skills:", student["skills"])

# Add a new key
student["college"] = "JECRC"

print("\nUpdated Dictionary:")
print(student)
