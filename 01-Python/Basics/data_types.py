# Python Data Types

name = "Yatharth"       # String
age = 20                # Integer
height = 1.70           # Float
student = True          # Boolean

numbers = [10, 20, 30]  # List
coordinates = (10, 20)  # Tuple
unique_numbers = {1, 2, 3}  # Set
person = {
    "name": "Yatharth",
    "age": 20
}                       # Dictionary

print(type(name))
print(type(age))
print(type(height))
print(type(student))
print(type(numbers))
print(type(coordinates))
print(type(unique_numbers))
print(type(person))
