# Python Lists

numbers = [10, 20, 30, 40, 50]

print("Original list:", numbers)

# Add an element
numbers.append(60)

# Remove an element
numbers.remove(20)

# Access element
print("First element:", numbers[0])

# Slice list
print("First three elements:", numbers[:3])

# Sort list
numbers.sort()

print("Updated list:", numbers)
